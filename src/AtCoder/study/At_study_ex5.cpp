// 問題
// 2つの整数A, Bが与えられます。
// A+Bの計算結果を出力してください。

// 制約
// 0≦A,B≦100
// A,Bは整数

#include <bits/stdc++.h>
using namespace std;

int main() {
    // 2つの整数A, Bを受け取る
    int int_A, int_B;

    // 入力
    cin >> int_A >> int_B; // LCOV_EXCL_BR_LINE
    // A+Bの計算結果を出力
    cout << (int_A + int_B) << "\n"; // LCOV_EXCL_BR_LINE
    return 0;
}
